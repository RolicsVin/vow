"""Создание ключей и подписи релизной сборки RuntimeProtector."""

from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey


def generate_keys(private_key_path: Path, public_header_path: Path) -> None:
    """Создаёт пару Ed25519 и записывает публичный ключ в C++ header."""
    if private_key_path.exists():
        raise FileExistsError(f'Файл закрытого ключа уже существует: {private_key_path}')

    private_key = Ed25519PrivateKey.generate()
    private_bytes = private_key.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public_bytes = private_key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )

    private_key_path.parent.mkdir(parents=True, exist_ok=True)
    private_key_path.write_text(private_bytes.hex() + '\n', encoding='ascii')
    try:
        os.chmod(private_key_path, 0o600)
    except OSError:
        pass

    rows = ',\n    '.join(
        ', '.join(f'0x{value:02x}' for value in public_bytes[index:index + 8])
        for index in range(0, len(public_bytes), 8)
    )
    header = (
        '#pragma once\n\n'
        '#include <cstdint>\n\n'
        '// Generated by tools/sign_release.py. Do not edit manually.\n'
        'inline constexpr uint8_t VOW_INTEGRITY_PUBLIC_KEY[32] = {\n'
        f'    {rows}\n'
        '};\n'
    )
    public_header_path.write_text(header, encoding='utf-8')
    print(f'Public key embedded into: {public_header_path}')
    print(f'Keep this private key offline: {private_key_path}')


def verify_authenticode_with_signtool(path: Path) -> None:
    """Проверяет Authenticode-подпись EXE или DLL через Windows SDK."""
    if sys.platform != 'win32':
        raise RuntimeError('Проверка Authenticode через signtool доступна только в Windows')

    result = subprocess.run(
        ['signtool.exe', 'verify', '/pa', '/v', str(path)],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f'Authenticode verification failed for {path}:\n'
            f'{result.stdout}\n{result.stderr}'
        )


def sha256_file(path: Path) -> str:
    """Вычисляет SHA-256 файла потоковым чтением."""
    digest = hashlib.sha256()
    with path.open('rb') as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def sign_release(
    private_key_path: Path,
    executable_path: Path,
    pck_path: Path,
    library_path: Path,
    output_directory: Path,
) -> None:
    """Создаёт манифест и Ed25519-подпись для трёх файлов релиза."""
    for path in (executable_path, pck_path, library_path):
        if not path.is_file():
            raise FileNotFoundError(f'Файл не найден: {path}')

    verify_authenticode_with_signtool(executable_path)
    verify_authenticode_with_signtool(library_path)

    private_bytes = bytes.fromhex(private_key_path.read_text(encoding='ascii').strip())
    if len(private_bytes) != 32:
        raise ValueError('Закрытый Ed25519-ключ должен содержать ровно 32 байта')

    private_key = Ed25519PrivateKey.from_private_bytes(private_bytes)
    manifest = (
        'VOW-INTEGRITY-V1\n'
        f'exe={sha256_file(executable_path)}\n'
        f'pck={sha256_file(pck_path)}\n'
        f'dll={sha256_file(library_path)}\n'
    ).encode('ascii')
    signature = private_key.sign(manifest)

    output_directory.mkdir(parents=True, exist_ok=True)
    (output_directory / 'integrity.manifest').write_bytes(manifest)
    (output_directory / 'integrity.sig').write_text(signature.hex() + '\n', encoding='ascii')
    print(f'Created: {output_directory / "integrity.manifest"}')
    print(f'Created: {output_directory / "integrity.sig"}')


def main() -> None:
    """Разбирает аргументы командной строки."""
    parser = argparse.ArgumentParser(description='RuntimeProtector release signing tool')
    commands = parser.add_subparsers(dest='command', required=True)

    keygen = commands.add_parser('keygen', help='Generate an Ed25519 key pair')
    keygen.add_argument('--private-key', type=Path, default=Path('keys/integrity_private.key'))
    keygen.add_argument(
        '--public-header',
        type=Path,
        default=Path('src/integrity_public_key.h'),
    )

    sign = commands.add_parser('sign', help='Sign a completed Windows release')
    sign.add_argument('--private-key', type=Path, required=True)
    sign.add_argument('--exe', type=Path, required=True)
    sign.add_argument('--pck', type=Path, required=True)
    sign.add_argument('--dll', type=Path, required=True)
    sign.add_argument('--output', type=Path, required=True)

    args = parser.parse_args()
    if args.command == 'keygen':
        generate_keys(args.private_key, args.public_header)
    else:
        sign_release(args.private_key, args.exe, args.pck, args.dll, args.output)


if __name__ == '__main__':
    main()
